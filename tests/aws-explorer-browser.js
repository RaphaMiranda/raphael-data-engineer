/* Execute in the rendered page with agent-browser eval --stdin or -b.
 * No production dependencies. Throws on failure, returns a concise report. */
(() => {
  const results = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  const $ = id => document.getElementById(id);
  const clickService = id => document.querySelector(`#service-list [data-service="${id}"]`).click();
  const details = () => $('study-details').textContent;
  const change = (id, value, type = 'change') => { $(id).value = value; $(id).dispatchEvent(new Event(type, { bubbles: true })); };
  $('clear-selection').click();
  $('reset-filters').click();
  assert(document.querySelectorAll('#service-list button').length === 75, 'All 75 services render');
  for (const s of window.awsExplorerData.services) {
    clickService(s.id);
    if (!details().includes(s.name) || !details().includes(s.recall.question) || !document.querySelector('#study-details details')) throw new Error(`Incomplete rendered card: ${s.id}`);
    if (document.querySelector(`#service-list [data-service="${s.id}"]`).getAttribute('aria-pressed') !== 'true') throw new Error(`List selection mismatch: ${s.id}`);
    if (document.querySelector(`#graph-world [data-service="${s.id}"]`).getAttribute('aria-pressed') !== 'true') throw new Error(`Graph selection mismatch: ${s.id}`);
    clickService(s.id);
  }
  assert(true, 'Every service card renders with recall and synchronized selection');
  clickService('s3');
  const summary = document.querySelector('#study-details summary');
  summary.click();
  assert(document.querySelector('#study-details details').open, 'Recall answer reveals');
  summary.click();
  assert(!document.querySelector('#study-details details').open, 'Recall answer hides');
  clickService('redshift');
  assert(['Redshift Spectrum', 'COPY from S3', 'UNLOAD to S3'].every(t => details().includes(t)), 'Required S3 + Redshift mechanisms render');
  assert(document.querySelectorAll('#selection-chips button').length === 2, 'Multiple selection chips render');
  change('service-search', 'missing-zzzz', 'input');
  assert($('service-list').textContent.includes('No services match'), 'No search results state renders');
  assert(document.querySelectorAll('#selection-chips button').length === 2 && document.querySelectorAll('.graph-node.selected').length === 2, 'Filters preserve working set and selected graph nodes');
  $('reset-filters').click();
  change('category-filter', 'Storage');
  assert(document.querySelectorAll('#service-list button').length === 6, 'Category filter narrows list');
  change('domain-filter', '2');
  assert(document.querySelectorAll('#service-list button').length === 6, 'Combined category/domain filter works');
  $('reset-filters').click();
  change('graph-pattern', 'spectrum');
  assert(document.querySelectorAll('.junction').length === 1 && $('graph-world').textContent.includes('Spectrum'), 'Map can focus a specific relationship');
  document.querySelector('[data-preset="rds,redshift,s3"]').click();
  assert(details().includes('Join operational and lake data in Redshift') && details().includes('Relationships involving a subset'), 'Required three-service example and subset section render');
  assert(details().includes('Secrets Manager') && details().includes('S3 is needed for the Spectrum branch only'), 'Prerequisites distinguish federation from Spectrum');
  document.querySelector('[data-remove="s3"]').click();
  assert(document.querySelectorAll('#selection-chips button').length === 2 && details().includes('Redshift federated queries'), 'Individual chip removal updates relationships');
  $('clear-selection').click();
  assert(!$('selection-chips').querySelector('button') && $('clear-selection').disabled, 'Clear-all restores empty working set');
  clickService('route53'); clickService('databrew');
  assert(details().includes('No verified relationship') && !document.querySelector('.relationship-card'), 'Honest unmatched-pair state renders');
  $('clear-selection').click();
  change('service-search', 'QuickSight', 'input');
  assert(document.querySelector('#service-list [data-service="quick"]'), 'Historical alias search works');
  $('reset-filters').click();
  const graph = $('graph-viewport');
  const before = $('graph-world').getAttribute('transform');
  graph.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  assert(before !== $('graph-world').getAttribute('transform'), 'Arrow-key pan works');
  $('fit-graph').click();
  const zoom = $('zoom-level').textContent;
  $('zoom-in').click();
  assert(zoom !== $('zoom-level').textContent, 'Zoom control works');
  $('fit-graph').click();
  assert(zoom === $('zoom-level').textContent, 'Fit restores overview zoom');
  const node = document.querySelector('#graph-world [data-service="s3"]');
  node.focus();
  node.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  assert(details().includes('Amazon S3') && document.activeElement.dataset.service === 's3', 'Graph keyboard selection preserves focus');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: ' ', bubbles: true }));
  assert(!$('selection-chips').querySelector('button'), 'Graph keyboard deselection works');
  assert(document.documentElement.scrollWidth <= window.innerWidth, 'No horizontal page overflow');
  assert([...document.querySelectorAll('button')].every(b => b.getBoundingClientRect().height >= 44), 'Button targets are at least 44px high');
  return { viewport: [window.innerWidth, window.innerHeight], checks: results.length, results };
})();
