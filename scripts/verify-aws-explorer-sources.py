"""Read official sources and record retrieval evidence; standard library only.

Run after content changes. A successful retrieval verifies the link, not every
editorial claim: review source text and the associated cards/relationships too.
"""
import concurrent.futures
import datetime
import hashlib
import json
import re
import subprocess
import sys
import urllib.request
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class Document(HTMLParser):
    def __init__(self):
        super().__init__()
        self.main = False
        self.title = False
        self.parts = []
        self.titles = []
        self.headings = []
        self.heading = False
        self.scope_entries = []
        self.in_li = False
        self.li_parts = []
        self.task_anchors = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if re.match(r'data-engineer-associate-01-domain\d-task\d+$', attrs.get('id', '')):
            self.task_anchors.append(attrs['id'])
        if attrs.get('id') == 'main-content':
            self.main = True
        if tag == 'title':
            self.title = True
        if self.main and tag in ('h1', 'h2', 'h3'):
            self.heading = True
        if self.main and tag == 'li':
            self.in_li = True
            self.li_parts = []

    def handle_endtag(self, tag):
        if tag == 'title':
            self.title = False
        if tag in ('h1', 'h2', 'h3'):
            self.heading = False
        if tag == 'li' and self.in_li:
            self.scope_entries.append(' '.join(' '.join(self.li_parts).split()))
            self.in_li = False

    def handle_data(self, value):
        if self.title:
            self.titles.append(value)
        if self.main:
            self.parts.append(value)
            if self.heading:
                self.headings.append(value)
            if self.in_li:
                self.li_parts.append(value)


data = json.loads(subprocess.check_output(
    ['node', '-e', "console.log(JSON.stringify(require('./assets/js/aws-explorer-data.js')))"],
    cwd=ROOT, encoding='utf-8'))
urls = sorted({data['scope']} | {d['source'] for d in data['domains']} |
              {u for s in data['services'] + data['relationships'] for u in s['sources']})
opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
cache = ROOT / '.tmp-aws-sources'
cache.mkdir(exist_ok=True)


def read(url):
    try:
        with opener.open(url, timeout=35) as response:
            raw = response.read()
            final = response.url
            status = response.status
        parser = Document()
        parser.feed(raw.decode('utf-8'))
        content = ' '.join(' '.join(parser.parts).split())
        title = ''.join(parser.titles)
        midpoint = len(title) // 2
        if title[:midpoint] == title[midpoint:]:
            title = title[:midpoint]
        filename = hashlib.sha256(url.encode()).hexdigest()[:16] + '.txt'
        (cache / filename).write_text(content, encoding='utf-8')
        result = dict(url=url, finalUrl=final, status=status, title=title,
                      retrieved=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                      sha256=hashlib.sha256(raw).hexdigest(), characters=len(content))
        if url == data['scope']:
            result['scopeEntries'] = parser.scope_entries
        if parser.task_anchors:
            result['taskAnchors'] = parser.task_anchors
        if len(content) < 100 or final != url:
            result['review'] = 'Check short page or redirect before accepting source'
        print(json.dumps({'url': url, 'title': title, 'intro': content[:250]}, ensure_ascii=True), flush=True)
        return result
    except Exception as error:
        print(json.dumps({'url': url, 'error': str(error)}), flush=True)
        return dict(url=url, error=str(error))


with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
    results = list(executor.map(read, urls))
destination = ROOT / 'docs/aws-explorer-source-audit.json'
destination.write_text(json.dumps({'retrievalDate': data['verified'], 'sources': results}, indent=2) + '\n', encoding='utf-8')
titles = {r['url']: r['title'].split(' - ')[0] for r in results if 'title' in r}
(ROOT / 'assets/js/aws-explorer-sources.js').write_text(
    '// Generated by scripts/verify-aws-explorer-sources.py; official page titles.\n'
    'window.awsExplorerData.sourceTitles = ' + json.dumps(titles, indent=2) + ';\n', encoding='utf-8')
sys.exit(1 if any('error' in r or 'review' in r for r in results) else 0)
